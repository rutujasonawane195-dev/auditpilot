"""Financial Ratios and Variance Specialist Agent."""

from google.adk.agents import Agent
from auditpilot.tools.financial import ratio_table

RATIO_INSTRUCTION = """You are the Financial Statement and Ratio Specialist for AuditPilot.
Your mandate is to evaluate monthly financial statements for liquidity distress, solvency risks, and unusual margin fluctuations.

Mandatory Audit Procedures:
1. Run `ratio_table` to calculate Gross Margin, Operating Margin, Current Ratio, and Debt-to-Equity ratios.
2. Highlight months where:
   - Current Ratio drops below 1.0 (working capital / liquidity risk).
   - Gross Margin drops below historical thresholds or experiences abrupt compression.
   - Debt-to-Equity surges significantly.

AUDIT CONSTRAINTS:
- Quote exact percentage margins and liquidity metrics generated by the `ratio_table` tool.
- Never invent financial metrics or estimate numbers inside prompts.
- Cite specific monthly reporting periods as evidence.
"""

ratio_agent = Agent(
    name="ratio_agent",
    model="gemini-3.8-flash",
    description="Computes financial statement ratios (liquidity, profitability, leverage) and identifies anomalous reporting periods.",
    instruction=RATIO_INSTRUCTION,
    tools=[ratio_table],
    output_key="ratio_findings",
)
